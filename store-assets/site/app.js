const analyticsMeasurementId = "G-J5G7MD2FNG";
const analyticsConsentKey = "sunny-spoon-analytics-consent";
const consentBanner = document.querySelector("#analyticsConsent");
let analyticsEnabled = false;

function trackEvent(name, parameters = {}) {
  if (!analyticsEnabled || typeof window.gtag !== "function") return;
  window.gtag("event", name, parameters);
}

function enableAnalytics() {
  if (analyticsEnabled) return;
  analyticsEnabled = true;
  window.dataLayer = window.dataLayer || [];
  window.gtag = function gtag() { window.dataLayer.push(arguments); };
  window.gtag("js", new Date());
  window.gtag("config", analyticsMeasurementId, { anonymize_ip: true });
  const script = document.createElement("script");
  script.async = true;
  script.src = `https://www.googletagmanager.com/gtag/js?id=${analyticsMeasurementId}`;
  document.head.append(script);
}

function applyAnalyticsChoice(choice) {
  localStorage.setItem(analyticsConsentKey, choice);
  consentBanner.hidden = true;
  if (choice === "granted") enableAnalytics();
}

document.querySelector("#acceptAnalytics")?.addEventListener("click", () => applyAnalyticsChoice("granted"));
document.querySelector("#declineAnalytics")?.addEventListener("click", () => applyAnalyticsChoice("denied"));
document.querySelector("#privacyChoices")?.addEventListener("click", () => { consentBanner.hidden = false; });

const savedAnalyticsChoice = localStorage.getItem(analyticsConsentKey);
if (savedAnalyticsChoice === "granted") enableAnalytics();
else if (savedAnalyticsChoice !== "denied") consentBanner.hidden = false;

