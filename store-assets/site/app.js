document.querySelectorAll("a[href]").forEach((link) => {
  link.addEventListener("click", () => {
    const href = link.getAttribute("href") || "";
    let destination = "internal";
    if (href.includes("apps.apple.com")) destination = "app_store";
    else if (href.includes("play.google.com")) destination = "google_play";
    else if (href.includes("youtube.com")) destination = "youtube";
    else if (href.startsWith("mailto:")) destination = "email";
    else if (href.includes("reportaproblem.apple.com")) destination = "apple_refund";
    else if (href.includes("support.google.com")) destination = "google_refund";
    else if (href.includes("privacy-policy")) destination = "privacy_policy";
    trackEvent("outbound_link_click", { destination, link_url: href });
  });
});
